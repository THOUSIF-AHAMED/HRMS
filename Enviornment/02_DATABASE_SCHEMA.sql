-- CREATE STANDARD GEN1 WAREHOUSE
USE ROLE SYSADMIN ;
CREATE OR REPLACE WAREHOUSE HRMS_GEN1_WH
WAREHOUSE_SIZE      = XSMALL  
SCALING_POLICY      = STANDARD  
GENERATION          = '1'
MIN_CLUSTER_COUNT   = 1        
MAX_CLUSTER_COUNT   = 2        
AUTO_RESUME         = TRUE           
AUTO_SUSPEND        = 120           
ENABLE_QUERY_ACCELERATION           = TRUE
QUERY_ACCELERATION_MAX_SCALE_FACTOR = 8 
MAX_CONCURRENCY_LEVEL               = 4
STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 30
STATEMENT_TIMEOUT_IN_SECONDS        = 900 ;  

-- GRANT PRIVILEGES ON WAREHOUSE
USE ROLE SECURITYADMIN ;
GRANT USAGE , OPERATE ON WAREHOUSE HRMS_GEN1_WH TO ROLE DATA_ENGINEER ;
GRANT MODIFY, MONITOR ON WAREHOUSE HRMS_GEN1_WH TO ROLE DATA_ENGINEER ;
