-- CREATE ACCOUNT LEVEL ROLE 
USE ROLE SECURITYADMIN ;
CREATE OR REPLACE ROLE DATA_ENGINEER ;
CREATE OR REPLACE ROLE DATA_ANALYST  ;

-- GRANT ROLE TO ANOTHER ROLE 
USE ROLE SECURITYADMIN ;
GRANT ROLE DATA_ENGINEER, DATA_ANALYST TO ROLE SYSADMIN ;
GRANT ROLE DATA_ENGINEER, DATA_ANALYST TO ROLE PUBLIC   ;

-- GRANT ROLE TO USER
USE ROLE SECURITYADMIN ;
GRANT ROLE DATA_ENGINEER, DATA_ANALYST TO USER THOUSIF ; 
GRANT ROLE DATA_ENGINEER, DATA_ANALYST TO USER AHAMED  ; 

-- CREATE SERVICE TYPE USER 
USE ROLE USERADMIN ;
CREATE OR REPLACE USER SVC_AHAMED
TYPE              = SERVICE 
DEFAULT_WAREHOUSE = DEV_WH  
DEFAULT_ROLE      = DATA_ENGINEER  
EMAIL             = 'mail.thousif@gmail.com' ;  

-- CREATE PERSON TYPE USER 
USE ROLE USERADMIN ;
CREATE OR REPLACE USER AHAMED 
